#include<iostream> 
using namespace std; 

int main(){
  int students; 

  students = 21; 
  //add
  students +=1; //+1
  students ++; //+1
  students = students + 1; //+1
  cout<<students<<endl;

  //substract 
  students -=1; //-1
  students --; //-1
  students = students - 1; //-1
  cout<<students<<endl;

  // Division 
  students /=1; // div 1
  students = students / 1; // div 1
  cout<<students<<endl;

  // Multiply
  students *=1; // div 1
  students = students * 1; // div 1
  cout<<students<<endl; 

  return 0; 
}